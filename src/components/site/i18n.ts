const EN_PATTERNS = Object.entries(EN)
  .filter(([key]) => key.includes("{0}"))
  .map(([key, value]) => {
    const source = key
      .split(/\{\d+\}/)
      .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
      .join("(.+?)");

    return { pattern: new RegExp(`^${source}$`), value };
  });

function lookup(text: string): string {
  if (EN[text] !== undefined) {
    return EN[text];
  }

  for (const { pattern, value } of EN_PATTERNS) {
    const match = text.match(pattern);

    if (match) {
      return match
        .slice(1)
        .reduce((result, arg, index) => result.replace(`{${index}}`, arg), value);
    }
  }

  return text;
}

export function tr(
  language: SiteLanguage,
  text: string,
  ...args: Array<string | number>
): string {
  let result = language === "en" ? lookup(text) : text;

  args.forEach((arg, index) => {
    result = result.replace(`{${index}}`, String(arg));
  });

  return result;
}

export function translateDeep<T>(value: T, language: SiteLanguage): T {
  if (language !== "en") {
    return value;
  }

  if (typeof value === "string") {
    return lookup(value) as T;
  }

  if (Array.isArray(value)) {
    return value.map((item) => translateDeep(item, language)) as T;
  }

  if (value && typeof value === "object" && Object.getPrototypeOf(value) === Object.prototype) {
    const result: Record<string, unknown> = {};

    for (const [key, item] of Object.entries(value)) {
      result[key] = translateDeep(item, language);
    }

    return result as T;
  }

  return value;
}
